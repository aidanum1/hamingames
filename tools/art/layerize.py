#!/usr/bin/env python3
"""
layerize.py — extract a clothing/hair layer from an "edited" generation of the
canonical base character.

Idea: every wardrobe item is generated by EDITING the canonical base image
(same pose, same framing). Pixels that differ between base and edit inside a
body region are the garment. We align the edit to the base (small translation
+ scale search anchored on a region that should not change), build a clean
difference mask, and export an RGBA layer on the base canvas.

Usage:
  python3 layerize.py --base base.png --edit edit.png --region x0,y0,x1,y1 \
      --anchor x0,y0,x1,y1 --out layer.png [--edit-alpha edit_nobg.png]
      [--thresh 28] [--debug debug.jpg] [--mode diff|alpha]

Coordinates are in base-image pixels. --mode alpha keeps every opaque pixel of
the (background-removed) edit inside the region instead of diffing — used for
whole-head replacement layers.
"""
import argparse
import numpy as np
from PIL import Image
from scipy import ndimage as ndi


def load_rgb(p, size=None):
    im = Image.open(p).convert('RGB')
    if size and im.size != size:
        im = im.resize(size, Image.LANCZOS)
    return np.asarray(im).astype(np.float32)


def load_alpha(p, size=None):
    im = Image.open(p)
    if size and im.size != size:
        im = im.resize(size, Image.LANCZOS)
    if im.mode != 'RGBA':
        im = im.convert('RGBA')
    return np.asarray(im)[..., 3].astype(np.float32) / 255.0


def box(s):
    return tuple(int(float(v)) for v in s.split(','))


def to_lab(rgb):
    """sRGB (0-255 float) -> CIE Lab (D65)."""
    c = rgb / 255.0
    c = np.where(c > 0.04045, ((c + 0.055) / 1.055) ** 2.4, c / 12.92)
    m = np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]], np.float32)
    xyz = c @ m.T / np.array([0.95047, 1.0, 1.08883], np.float32)
    f = np.where(xyz > 0.008856, np.cbrt(xyz), 7.787 * xyz + 16 / 116)
    L = 116 * f[..., 1] - 16
    a = 500 * (f[..., 0] - f[..., 1])
    b = 200 * (f[..., 1] - f[..., 2])
    return np.stack([L, a, b], -1)


def gray(a):
    return a[..., 0] * 0.299 + a[..., 1] * 0.587 + a[..., 2] * 0.114


def warp(img, scale, dx, dy, order=1, cval=0.0):
    """Scale about the image center then translate. Works on HxW or HxWxC."""
    h, w = img.shape[:2]
    cy, cx = h / 2.0, w / 2.0
    # output(y,x) = input((y - cy - dy)/s + cy, (x - cx - dx)/s + cx)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    sy = (yy - cy - dy) / scale + cy
    sx = (xx - cx - dx) / scale + cx
    if img.ndim == 2:
        return ndi.map_coordinates(img, [sy, sx], order=order, cval=cval, mode='constant')
    return np.stack([ndi.map_coordinates(img[..., c], [sy, sx], order=order, cval=cval, mode='constant')
                     for c in range(img.shape[2])], axis=-1)


def align(base, edit, anchor, search=48, scales=(0.97, 0.98, 0.99, 1.0, 1.01, 1.02, 1.03)):
    """Find scale/dx/dy so warp(edit) best matches base inside the anchor box."""
    x0, y0, x1, y1 = anchor
    f = 4  # downsample factor for the coarse search
    gb = gray(base)[::f, ::f]
    ge_full = gray(edit)
    a = (x0 // f, y0 // f, x1 // f, y1 // f)
    ref = gb[a[1]:a[3], a[0]:a[2]]
    ref = (ref - ref.mean()) / (ref.std() + 1e-6)
    best = (-1e9, 1.0, 0, 0)
    for s in scales:
        ge = warp(ge_full, s, 0, 0)[::f, ::f] if s != 1.0 else ge_full[::f, ::f]
        r = search // f
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                ys, xs = a[1] - dy, a[0] - dx
                if ys < 0 or xs < 0 or ys + ref.shape[0] > ge.shape[0] or xs + ref.shape[1] > ge.shape[1]:
                    continue
                cand = ge[ys:ys + ref.shape[0], xs:xs + ref.shape[1]]
                cand = (cand - cand.mean()) / (cand.std() + 1e-6)
                score = float((ref * cand).mean())
                if score > best[0]:
                    best = (score, s, dx * f, dy * f)
    # refine translation at full resolution (+-f px)
    score0, s, bdx, bdy = best
    gbf = gray(base)[y0:y1, x0:x1]
    gbf = (gbf - gbf.mean()) / (gbf.std() + 1e-6)
    ge = warp(ge_full, s, 0, 0) if s != 1.0 else ge_full
    for dy in range(bdy - f, bdy + f + 1):
        for dx in range(bdx - f, bdx + f + 1):
            ys, xs = y0 - dy, x0 - dx
            if ys < 0 or xs < 0 or ys + gbf.shape[0] > ge.shape[0] or xs + gbf.shape[1] > ge.shape[1]:
                continue
            cand = ge[ys:ys + gbf.shape[0], xs:xs + gbf.shape[1]]
            cand = (cand - cand.mean()) / (cand.std() + 1e-6)
            sc = float((gbf * cand).mean())
            if sc > best[0]:
                best = (sc, s, dx, dy)
    return best


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', required=True)
    ap.add_argument('--edit', required=True)
    ap.add_argument('--edit-alpha')
    ap.add_argument('--region', required=True, help='x0,y0,x1,y1 (base px) where the item may appear')
    ap.add_argument('--exclude', action='append', default=[], help='x0,y0,x1,y1 boxes to exclude (repeatable)')
    ap.add_argument('--anchor', required=True, help='x0,y0,x1,y1 region expected to be unchanged, for alignment')
    ap.add_argument('--out', required=True)
    ap.add_argument('--thresh', type=float, default=9.0, help='Lab deltaE threshold')
    ap.add_argument('--min-frac', type=float, default=0.002, help='drop components smaller than this fraction of region')
    ap.add_argument('--close', type=int, default=8)
    ap.add_argument('--mode', default='diff', choices=['diff', 'alpha'])
    ap.add_argument('--feather-bottom', type=int, default=0, help='alpha ramp height (px) at the bottom of the region (head layers)')
    ap.add_argument('--no-align', action='store_true')
    ap.add_argument('--debug')
    args = ap.parse_args()

    base_im = Image.open(args.base)
    size = base_im.size
    base = load_rgb(args.base)
    edit = load_rgb(args.edit, size)
    ealpha = load_alpha(args.edit_alpha, size) if args.edit_alpha else None

    if args.no_align:
        sc, s, dx, dy = 1.0, 1.0, 0, 0
    else:
        sc, s, dx, dy = align(base, edit, box(args.anchor))
    print(f'align: score={sc:.3f} scale={s} dx={dx} dy={dy}')
    if (s, dx, dy) != (1.0, 0, 0):
        edit = warp(edit, s, dx, dy, cval=255.0)
        if ealpha is not None:
            ealpha = warp(ealpha, s, dx, dy, cval=0.0)

    h, w = base.shape[:2]
    region = np.zeros((h, w), bool)
    x0, y0, x1, y1 = box(args.region)
    region[y0:y1, x0:x1] = True
    for ex in args.exclude:
        ex0, ey0, ex1, ey1 = box(ex)
        region[ey0:ey1, ex0:ex1] = False

    if args.mode == 'diff':
        bb = ndi.gaussian_filter(base, sigma=(1.5, 1.5, 0))
        eb = ndi.gaussian_filter(edit, sigma=(1.5, 1.5, 0))
        d = np.sqrt(((to_lab(bb) - to_lab(eb)) ** 2).sum(-1))
        m = (d > args.thresh) & region
        m = ndi.binary_opening(m, iterations=2)
        m = ndi.binary_closing(m, iterations=args.close)
        m = ndi.binary_fill_holes(m)
        lab, n = ndi.label(m)
        if n:
            sizes = ndi.sum(m, lab, range(1, n + 1))
            keep = np.zeros(n + 1, bool)
            keep[1:] = sizes >= args.min_frac * region.sum()
            m = keep[lab]
        m = ndi.binary_dilation(m, iterations=2) & region
        alpha = ndi.gaussian_filter(m.astype(np.float32), 1.0)
    else:
        alpha = region.astype(np.float32)

    if ealpha is not None:
        alpha = alpha * ealpha
    if args.feather_bottom > 0:
        ramp = np.ones(h, np.float32)
        fb = args.feather_bottom
        ramp[y1 - fb:y1] = np.linspace(1, 0, fb)
        alpha = alpha * ramp[:, None]
    alpha = np.clip(alpha, 0, 1)

    out = np.dstack([edit, alpha * 255.0]).clip(0, 255).astype(np.uint8)
    Image.fromarray(out, 'RGBA').save(args.out)
    cov = float((alpha > 0.5).sum()) / max(1, region.sum())
    print(f'wrote {args.out} coverage={cov:.3f}')

    if args.debug:
        vis = base.copy()
        tint = np.array([255, 0, 180], np.float32)
        a3 = (alpha > 0.5)[..., None]
        vis = np.where(a3, vis * 0.4 + tint * 0.6, vis * 0.85)
        vis[~region] *= 0.6
        im = Image.fromarray(vis.clip(0, 255).astype(np.uint8))
        im.thumbnail((600, 800))
        im.save(args.debug, quality=85)


if __name__ == '__main__':
    main()
